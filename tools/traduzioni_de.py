def main():
    html_path = Path(__file__).resolve().parent.parent / "index.html"
    html = html_path.read_text(encoding="utf-8")
    pat = re.compile(r'(<script type="application/json" id="i18n">)(.*?)(</script>)', re.S)
    if not pat.search(html):
        raise SystemExit('Blocco <script id="i18n"> non trovato in index.html')
    # una voce per riga: si legge e si corregge facilmente anche in index.html
    righe = ",\n".join(f"{json.dumps(k, ensure_ascii=False)}:{json.dumps(v, ensure_ascii=False)}" for k, v in DE.items())
    payload = '{"de":{\n' + righe.replace("</", "<\\/") + "\n}}"
    html_path.write_text(pat.sub(lambda m: m.group(1) + payload + m.group(3), html, count=1), encoding="utf-8")
    print(f"{len(DE)} voci scritte nel dizionario tedesco di index.html. Ora cambia VERSION in sw.js.")


if __name__ == "__main__":
    main()
